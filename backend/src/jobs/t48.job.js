'use strict';

const { Queue, Worker } = require('bullmq');
const { connection, onWorkerError } = require('../config/bullmq');
const meetingRepository  = require('../repositories/meeting.repository');
const auditLogRepository = require('../repositories/audit-log.repository');
const reportService      = require('../services/report.service');
const emailService       = require('../services/email.service');
const logger             = require('../utils/logger');

const QUEUE_NAME      = 'meeting-t48';
const SCAN_INTERVAL_MS = 5 * 60 * 1000; // poll every 5 minutes

let queue  = null;
let worker = null;

// Core logic — called by the worker on each scheduled tick.
async function processT48() {
  const meetings = await meetingRepository.findDueT48();
  if (meetings.length === 0) return;

  logger.info('T-48 job: meetings due for workflow trigger', { count: meetings.length });

  for (const meeting of meetings) {
    try {
      const updated = await meetingRepository.triggerWorkflow(meeting.id);
      await auditLogRepository.create(
        updated.tenantId,
        'system@bmmj.internal',
        'Remediation Workflow Triggered',
        { meetingId: meeting.id, trigger: 't48-scheduler', scheduledStart: meeting.scheduledStart }
      );
      logger.info('T-48 job: workflow triggered', {
        meetingId: meeting.id,
        tenantId:  meeting.tenantId,
        title:     meeting.title,
      });

      // AI recommendations are now generated by nxg360Prefetch.job.js at T-24,
      // where NXG360 data is guaranteed fresh. T-48 owns workflow + notifications only.

      reportService.autoGenerateMonthlyReport(meeting.id, meeting.tenantId)
        .catch((err) => logger.error('T-48: monthly report auto-generate failed', {
          meetingId: meeting.id, tenantId: meeting.tenantId, error: err.message,
        }));

      // Queue reminder emails to all assigned AMs + meeting attendees.
      emailService.queueMeetingReminderEmails(meeting.id, meeting.tenantId)
        .catch((err) => logger.error('T-48: reminder email queuing failed', {
          meetingId: meeting.id, tenantId: meeting.tenantId, error: err.message,
        }));
    } catch (err) {
      // Log and continue — one failing meeting must not block the rest.
      logger.error('T-48 job: failed to trigger workflow for meeting', {
        meetingId: meeting.id,
        tenantId:  meeting.tenantId,
        error:     err.message,
      });
    }
  }
}

async function start() {
  try {
    queue = new Queue(QUEUE_NAME, {
      connection,
      defaultJobOptions: {
        removeOnComplete: { count: 100 },
        removeOnFail:     { count: 50  },
      },
    });

    worker = new Worker(
      QUEUE_NAME,
      async () => { await processT48(); },
      { connection, concurrency: 1 }
    );

    worker.on('completed', (job) => {
      logger.info('T-48 worker: scan completed', { jobId: job.id });
    });

    worker.on('failed', (job, err) => {
      logger.error('T-48 worker: scan failed', { jobId: job?.id, error: err.message });
    });

    // Handles Redis connection drops — must be attached or Node throws UnhandledRejection.
    worker.on('error', onWorkerError('T-48 worker'));

    // upsertJobScheduler is idempotent — safe to call on every server restart.
    // BullMQ v5 deduplicates by scheduler ID and updates the interval if it changed.
    await queue.upsertJobScheduler(
      't48-scan-scheduler',
      { every: SCAN_INTERVAL_MS },
      { name: 'scan', data: {} }
    );

    logger.info('T-48 scheduler started', { intervalMs: SCAN_INTERVAL_MS });
  } catch (err) {
    // Redis being unavailable must not crash the server — all other features still work.
    logger.error('T-48 scheduler failed to start — Redis may be unavailable', {
      error: err.message,
    });
  }
}

async function stop() {
  try {
    if (worker) await worker.close();
    if (queue)  await queue.close();
    logger.info('T-48 scheduler stopped');
  } catch (err) {
    logger.warn('T-48 scheduler stop error', { error: err.message });
  }
}

module.exports = { start, stop };
